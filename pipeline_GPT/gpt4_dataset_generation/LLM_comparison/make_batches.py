"""Converts paired model responses into OpenAI API chat format using base64-encoded images."""

import json
import os
from tqdm import tqdm
import pandas as pd

TSV_PATH = "/mloscratch/users/mberruye/evaluation/GMAI-MMBench/GMAI-MMBench_VAL.tsv"
MODEL_NAME = "gpt-4o"
MAX_TOKENS = 256

# Cleaned model outputs
GEMMA_PATH = "/mloscratch/users/mberruye/evaluation/outputs_benchmarks/gemma/cleaned_answers.jsonl"
QWEN_PATH = "/mloscratch/users/mberruye/evaluation/outputs_benchmarks/qwen/cleaned_answers.jsonl"

OUTPUT_DIR = "batches_comparison/gemma_vs_qwen"

BASE_PROMPT = (
    "You are a medical expert comparing two answers generated by different language models based on the same medical image.\n"
    "You will be given:\n"
    "- A medical question\n"
    "- Two different model-generated free-text responses\n"
    "- The associated image\n\n"
    "Compare the two responses based on the following criteria, each scored from 1 (very poor) to 5 (excellent):\n"
    "1. Accuracy: Are the clinical facts correct?\n"
    "2. Completeness: Does the response address all critical elements of the question?\n"
    "3. Instruction Following: Does the model appropriately follow the instructions or question intent?\n"
    "4. Communication: Is the response clearly written, coherent, and professionally phrased?\n"
    "5. Context Awareness: Does the model account for relevant clinical or conversational context?\n\n"
    "After evaluating the criteria above, determine which model gave the better response. Only choose one of the following:\n"
    '- \"model_a\" (if Response A is clearly better)\n'
    '- \"model_b\" (if Response B is clearly better)\n'
    '- \"tie\" (if they are approximately equal)\n\n'
    "Return only the following JSON structure:\n"
    "{\n"
    "  \"preferred_model\": \"model_a\" | \"model_b\" | \"tie\"\n"
    "}"
)

def load_answers(path):
    with open(path, "r") as f:
        return {json.loads(line)["index"]: json.loads(line) for line in f}

def load_image_data():
    df = pd.read_csv(TSV_PATH, sep="\t")
    df.set_index("index", inplace=True)
    return df

def process_entry(index, question, response_a, response_b, image_b64, request_id):
    prompt = (
        BASE_PROMPT +
        f"\n\nQuestion: {question}\n\nResponse A:\n{response_a}\n\nResponse B:\n{response_b}"
    )

    messages = [
        {"role": "system", "content": "You are an expert medical evaluator."},
        {
            "role": "user",
            "content": [
                {"type": "text", "text": prompt},
                {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image_b64}"}}
            ]
        }
    ]

    return {
        "custom_id": f"request-{request_id}",
        "method": "POST",
        "url": "/v1/chat/completions",
        "body": {
            "model": MODEL_NAME,
            "messages": messages,
            "max_tokens": MAX_TOKENS
        }
    }

def process_dataset(output_dir, gemma_path, qwen_path, max_size=0.18 * 1024**3):
    os.makedirs(output_dir, exist_ok=True)
    gemma = load_answers(gemma_path)
    qwen = load_answers(qwen_path)
    df_tsv = load_image_data()
    shared_indices = sorted(set(gemma.keys()) & set(qwen.keys()) & set(df_tsv.index))

    file_number = 1
    current_file_size = 0
    current_file_path = os.path.join(output_dir, f"part_{file_number}.jsonl")
    current_file = open(current_file_path, "w")

    for idx in tqdm(shared_indices, desc="Building comparison batches"):
        question = gemma[idx]["question"]
        response_a = gemma[idx]["output"]
        response_b = qwen[idx]["output"]
        image_b64 = df_tsv.loc[idx, "image"]

        api_request = process_entry(idx, question, response_a, response_b, image_b64, request_id=idx)
        json_str = json.dumps(api_request) + "\n"
        json_size = len(json_str.encode("utf-8"))

        if current_file_size + json_size > max_size:
            current_file.close()
            file_number += 1
            current_file_path = os.path.join(output_dir, f"part_{file_number}.jsonl")
            current_file = open(current_file_path, "w")
            current_file_size = 0

        current_file.write(json_str)
        current_file_size += json_size

    current_file.close()
    print(f"Saved {file_number} batch files to {output_dir}.")

if __name__ == "__main__":
    process_dataset(OUTPUT_DIR, GEMMA_PATH, QWEN_PATH)
