"""Converts Llava pretrain dataset to OpenAI API request format."""
 
from utils import load_data
import json
import os
from tqdm import tqdm
import base64
import pandas as pd


TSV_PATH = "/mloscratch/users/mberruye/evaluation/GMAI-MMBench/GMAI-MMBench_VAL.tsv"
MODEL_NAME = "gpt-4o"
MAX_TOKENS = 256
FILE_ID_MAPPING_PATH = "/mloscratch/users/nemo/benchmarking/file_map.json"


# List of (JSONL_PATH, OUTPUT_DIR) for each model
model_paths = [
    ("/mloscratch/users/mberruye/evaluation/outputs_benchmarks/multimeditron/cleaned_answers.jsonl",
        "batches_eval/multimeditron"),
    ("/mloscratch/users/mberruye/evaluation/outputs_benchmarks/gemma/cleaned_answers.jsonl",
        "batches_eval/gemma"),
    ( "/mloscratch/users/mberruye/evaluation/outputs_benchmarks/qwen/cleaned_answers.jsonl",
        "batches_eval/qwen")
]

BASE_PROMPT = (
    "You are a medical expert reviewing answers generated by a language model based on medical images.\n"
    "You will be given:\n"
    "- A medical question\n"
    "- A model-generated free-text response\n"
    "- The associated image\n\n"
    "Evaluate the response on the following dimensions, each scored from 1 (very poor) to 5 (excellent):\n"
    "1. Accuracy: Are the clinical facts correct?\n"
    "2. Completeness: Does the response address all critical elements of the question?\n"
    "3. Instruction Following: Does the model appropriately follow the instructions or question intent?\n"
    "4. Communication: Is the response clearly written, coherent, and professionally phrased?\n"
    "5. Context Awareness: Does the model account for relevant clinical or conversational context?\n\n"
    "Return only the evaluation in the following JSON format:\n"
    "{\n"
    '  "accuracy": X,\n'
    '  "completeness": X,\n'
    '  "instruction_following": X,\n'
    '  "communication": X,\n'
    '  "context_awareness": X\n'
    "}\n"
    "Do not explain your scores. Do not include any other text."
)


def load_file_id_map():
    with open(FILE_ID_MAPPING_PATH, "r") as f:
        raw_map = json.load(f)
    return {
        os.path.splitext(os.path.basename(path))[0]: file_id
        for path, file_id in raw_map.items()
    }

def load_data(cleaned_jsonl, file_id_map):
    with open(cleaned_jsonl, "r") as f:
        cleaned_entries = [json.loads(line) for line in f]

    df_tsv = pd.read_csv(TSV_PATH, sep="\t")
    df_tsv.set_index("index", inplace=True)

    examples = []
    for entry in cleaned_entries:
        idx = entry["index"]
        idx_str = str(idx)
        if idx in df_tsv.index and idx_str in file_id_map:
            file_id = file_id_map[idx_str]
            examples.append((idx, entry["question"], entry["output"], file_id))

    return examples

def process_entry(index, question, output, file_id, request_id):

    prompt = (
        BASE_PROMPT +
        f"\n\nQuestion: {question}\n\nModel Response: {output}\n"
    )

    messages = [
        {"role": "user", 
            "content": [
                        {
                            "type": "image_url",
                            "image_url": {
                                "url": f"openai://file/{file_id}"
                            }
                        },
                        {
                            "type": "text",
                            "text": prompt
                        }
                    ]}
    ]
  
    return {
        "custom_id": f"request-{request_id}",
        "method": "POST",
        "url": "/v1/chat/completions",
        "body": {
            "model": MODEL_NAME,
            "messages": messages,
            "max_tokens": MAX_TOKENS
        }
    }


def process_dataset(output_dir, cleaned_jsonl,file_id_map, max_size=0.18 * 1024**3):
    """
    Process the dataset and save the preprocessed data into multiple files (<=180MB) because of the max of the API,
    each not exceeding a specified size.
 
    Args:
        output_dir (str): Directory to save the preprocessed data.
        max_size (int): Maximum size of each file in bytes.
    """

    os.makedirs(output_dir, exist_ok=True)

    examples = load_data(cleaned_jsonl, file_id_map)
 
    file_number = 1
    current_file_size = 0
    current_file_path = os.path.join(output_dir, f"part_{file_number}.jsonl")
    current_file = open(current_file_path, "w")

    for i, (index, question, output, file_id) in tqdm(enumerate(examples), total=len(examples), desc="Processing dataset"):
        api_request = process_entry(index, question, output, file_id, request_id=index)
        json_str = json.dumps(api_request) + "\n"
        json_size = len(json_str.encode("utf-8"))

        # Check if adding this JSON string exceeds the maximum file size
        if current_file_size + json_size > max_size:
            current_file.close()
            file_number += 1
            current_file_path = os.path.join(output_dir, f"part_{file_number}.jsonl")
            current_file = open(current_file_path, "w")
            current_file_size = 0

        current_file.write(json_str)
        current_file_size += json_size
 
    current_file.close()
    print(f"Preprocessed data saved to {output_dir} in {file_number} files.")

if __name__ == "__main__":
    file_id_map = load_file_id_map()
    for CLEANED_JSONL, OUTPUT_DIR in model_paths:
        process_dataset(OUTPUT_DIR, CLEANED_JSONL, file_id_map)