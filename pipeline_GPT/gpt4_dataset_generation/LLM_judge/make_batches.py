BASE_PROMPT = (
    "You are a medical expert reviewing answers generated by a language model based on medical images.\n"
    "You will be given:\n"
    "- A medical question\n"
    "- A model-generated free-text response\n"
    "- The associated image\n\n"
    "Evaluate the response on the following dimensions, each scored from 1 (very poor) to 5 (excellent):\n"
    "1. Accuracy: Are the clinical facts correct?\n"
    "2. Completeness: Does the response address all critical elements of the question?\n"
    "3. Instruction Following: Does the model appropriately follow the instructions or question intent?\n"
    "4. Communication: Is the response clearly written, coherent, and professionally phrased?\n"
    "5. Context Awareness: Does the model account for relevant clinical or conversational context?\n\n"
    "Return only the evaluation in the following JSON format:\n"
    "{\n"
    '  "accuracy": X,\n'
    '  "completeness": X,\n'
    '  "instruction_following": X,\n'
    '  "communication": X,\n'
    '  "context_awareness": X\n'
    "}\n"
    "Do not explain your scores. Do not include any other text."
)



def load_data(cleaned_jsonl):
    with open(cleaned_jsonl, "r") as f:
        cleaned_entries = [json.loads(line) for line in f]

    df_tsv = pd.read_csv(TSV_PATH, sep="\t")
    df_tsv.set_index("index", inplace=True)

    examples = []
    for entry in cleaned_entries:
        idx = entry["index"]
        if idx in df_tsv.index:
            image_b64 = df_tsv.loc[idx, "image"]  # Already base64-encoded
            examples.append((idx, entry["question"], entry["output"], image_b64))

    return examples

def process_entry(index, question, output, image_b64, request_id):
    messages = [{"role": "system", "content": "You are an expert assistant."}]

    prompt = (
        BASE_PROMPT +
        f"\n\nQuestion: {question}\n\nModel Response: {output}\n"
    )

    messages.append({
        "role": "user",
        "content": [
            {"type": "text", "text": prompt},
            {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image_b64}"}}
        ]
    })

    return {
        "custom_id": f"request-{request_id}",
        "method": "POST",
        "url": "/v1/chat/completions",
        "body": {
            "model": MODEL_NAME,
            "messages": messages,
            "max_tokens": MAX_TOKENS
        }
    }


def process_dataset(output_dir, cleaned_jsonl, max_size=0.18 * 1024**3):
    """
    Process the dataset and save the preprocessed data into multiple files (<=180MB) because of the max of the API,
    each not exceeding a specified size.
 
    Args:
        output_dir (str): Directory to save the preprocessed data.
        max_size (int): Maximum size of each file in bytes.
    """

    os.makedirs(output_dir, exist_ok=True)

    examples = load_data(cleaned_jsonl)
 
    file_number = 1
    current_file_size = 0
    current_file_path = os.path.join(output_dir, f"part_{file_number}.jsonl")
    current_file = open(current_file_path, "w")

    for i, (index, question, output, image_b64) in tqdm(enumerate(examples), total=len(examples), desc="Processing dataset"):
        api_request = process_entry(index, question, output, image_b64, request_id=index)
        json_str = json.dumps(api_request) + "\n"
        json_size = len(json_str.encode("utf-8"))

        # Check if adding this JSON string exceeds the maximum file size
        if current_file_size + json_size > max_size:
            current_file.close()
            file_number += 1
            current_file_path = os.path.join(output_dir, f"part_{file_number}.jsonl")
            current_file = open(current_file_path, "w")
            current_file_size = 0

        current_file.write(json_str)
        current_file_size += json_size
 
    current_file.close()
    print(f"Preprocessed data saved to {output_dir} in {file_number} files.")

if __name__ == "__main__":
    for CLEANED_JSONL, OUTPUT_DIR in model_paths:
        process_dataset(OUTPUT_DIR, CLEANED_JSONL)
